"""Shared C++ helpers of the hub for the YAML lambdas (enable with an empty `immergas_core:` block).

served_value.h - which value from the D+/D- bus may replace a value the hub serves to the boiler
fault_texts.h  - boiler fault texts in 11 languages (generated by tools/gen_fault_texts.py)
mt_fault_texts.h - MAGIS M (Midea M-Thermal) fault codes and texts, en / pl (generated by tools/gen_mt_fault_texts.py)
bus_map.h      - registers / PDUs seen on D+/D- and T-/T+ (min / max / changes) for the bus map report
"""
import esphome.codegen as cg
import esphome.config_validation as cv

CODEOWNERS = ["@jotuera"]

CONFIG_SCHEMA = cv.Schema({})


async def to_code(config):
    # standard headers used by the lambdas of the dd_ packages
    for std in ("array", "algorithm", "climits"):
        cg.add_global(cg.RawStatement(f"#include <{std}>"))
    for header in ("served_value.h", "fault_texts.h", "mt_fault_texts.h", "bus_map.h"):
        cg.add_global(cg.RawStatement(f'#include "esphome/components/immergas_core/{header}"'))
