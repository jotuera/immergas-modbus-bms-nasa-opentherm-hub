"""Regenerates src/esp_names.ts: the names of the ot_ / gb_ / mt_ entities in the other languages of the packages.

The cards find the ESP OpenTherm, gas boiler and MAGIS M hubs by entity name (hub.ts, ESP_OT / ESP_GB / ESP_MT with
the Polish and English names). This script maps every Polish name to the same entity's name in the other languages
(packages/lang/<pkg>_<lang>.yaml, the n_* keys, without the "${<pkg>_name_prefix} - " part), and hub.ts adds them.
Usage: python tools/gen_esp_names.py   (run from the cards folder)
"""
import os, re, json

HERE = os.path.dirname(os.path.abspath(__file__))
CARDS = os.path.dirname(HERE)
HUB = os.path.dirname(CARDS)
LANGS = ["cs", "de", "es", "fr", "hu", "it", "nl", "pt", "sk"]
PKGS = ["ot", "gb", "mt"]
LINE = re.compile(r'^  (n_[a-z0-9_]+):\s*"?(.*?)"?\s*$')


def names(pkg, lang):
    p = os.path.join(HUB, "packages", "lang", f"{pkg}_{lang}.yaml")
    if not os.path.exists(p):
        return {}
    out = {}
    for line in open(p, encoding="utf-8"):
        m = LINE.match(line.rstrip("\n"))
        if not m:
            continue
        v = m.group(2).replace('\\"', '"')
        v = re.sub(r"^\$\{[a-z0-9_]+\} - ", "", v)
        out[m.group(1)] = v
    return out


def main():
    data = {}
    for pkg in PKGS:
        pl = names(pkg, "pl")
        others = {l: names(pkg, l) for l in LANGS}
        m = {}
        for k, v in pl.items():
            alt = []
            for l in LANGS:
                x = others[l].get(k)
                if x and x != v and x not in alt:
                    alt.append(x)
            if alt and "${" not in v:
                m[v] = alt
        data[pkg] = m
    out = ["// Generated by tools/gen_esp_names.py from the language files of the ot_ / gb_ / mt_ packages - do not edit by hand.",
           "// package -> Polish entity name -> the same entity's name in the other languages (cs de es fr hu it nl pt sk).",
           "export const ESP_LANGS: Record<string, Record<string, string[]>> = " + json.dumps(data, ensure_ascii=False, indent=1) + ";", ""]
    dst = os.path.join(CARDS, "src", "esp_names.ts")
    open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(dst, {k: len(v) for k, v in data.items()})


if __name__ == "__main__":
    main()
