#!/usr/bin/env python3
"""Generate components/immergas_core/mt_fault_texts.h from tools/mt_fault_texts.json (MAGIS M / Midea M-Thermal faults).

Usage: python tools/gen_mt_fault_texts.py   (run from the repository root)
The JSON holds the Modbus fault number (registers 124-127), the display code and the project's own texts (en, pl).
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "mt_fault_texts.json")
DST = os.path.join(ROOT, "components", "immergas_core", "mt_fault_texts.h")
LANGS = ["en", "pl"]
MAX = 250


def c(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    d = json.load(open(SRC, encoding="utf-8"))
    rows = sorted(d["faults"], key=lambda r: r["n"])
    for r in rows:
        for l in LANGS:
            full = f'{r["code"]}: {r[l]}'
            assert len(full.encode("utf-8")) <= MAX, (r["code"], l, len(full.encode("utf-8")))
    n = len(rows)
    out = ["#pragma once",
           "// MAGIS M (Midea M-Thermal) fault texts for the mt_ packages: Modbus fault number (registers 124-127) -> display",
           "// code and description. GENERATED by tools/gen_mt_fault_texts.py from tools/mt_fault_texts.json (the project's own",
           "// wording; numbers and codes from the MAGIS M4-30 manual, chap. 13.4) - do not edit.",
           "// Part of jotuera/immergas-modbus-bms-nasa-opentherm-hub - PolyForm Noncommercial 1.0.0 (c) 2026 JoTu.",
           "#include <cstddef>", "#include <cstdint>", "#include <string>", "", "namespace immergas {", "",
           f"static const uint16_t kMtFaultNums[{n}] = {{" + ", ".join(str(r["n"]) for r in rows) + "};",
           f"static const char *const kMtFaultCodes[{n}] = {{" + ", ".join(c(r["code"]) for r in rows) + "};", ""]
    for l in LANGS:
        out.append(f"static const char *const kMtFaults_{l}[{n}] = {{")
        out += [f"    {c(r[l])}," for r in rows]
        out.append("};")
    out += ["",
            f'static const char *const kMtNone[2] = {{{c(d["none"]["en"])}, {c(d["none"]["pl"])}}};',
            f'static const char *const kMtUnknown[2] = {{{c(d["unknown"]["en"])}, {c(d["unknown"]["pl"])}}};',
            "",
            "// index of the fault number, or -1",
            "inline int mt_fault_index(int num) {",
            f"  for (int i = 0; i < {n}; i++)",
            "    if (kMtFaultNums[i] == num) return i;",
            "  return -1;",
            "}",
            "",
            "// display code of a fault number (\"E8\"), \"#<number>\" for an unknown one, \"-\" for 0",
            "inline std::string mt_fault_code(int num) {",
            "  if (num == 0) return \"-\";",
            "  int i = mt_fault_index(num);",
            "  return i < 0 ? \"#\" + std::to_string(num) : std::string(kMtFaultCodes[i]);",
            "}",
            "",
            "// \"E8: <description>\"; lang = the index of the immergas_core fault languages (2 = Polish, anything else = English)",
            "inline std::string mt_fault_description(int num, size_t lang) {",
            "  size_t l = lang == 2 ? 1 : 0;",
            "  if (num == 0) return kMtNone[l];",
            "  int i = mt_fault_index(num);",
            "  if (i < 0) return \"#\" + std::to_string(num) + \": \" + kMtUnknown[l];",
            "  return std::string(kMtFaultCodes[i]) + \": \" + (l ? kMtFaults_pl[i] : kMtFaults_en[i]);",
            "}",
            "", "}  // namespace immergas", ""]
    open(DST, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"{DST}: {n} faults")


if __name__ == "__main__":
    main()
